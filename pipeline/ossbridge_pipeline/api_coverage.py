#!/usr/bin/env python3
"""
================================================================================
Step 6: Coverage of Each API
================================================================================

Joins the API of the library (apis.csv, step 4) with the JaCoCo report of its
test suite (coverage.xml, step 5). Every method and constructor gets a status:

    covered              the tests ran at least one of its instructions
    covered_by_override  its own body was not run (or it has none), but the tests
                         ran a library method that overrides or implements it:
                         a call to the API runs that method (virtual dispatch,
                         e.g. JsonNode.get(String) -> ObjectNode.get(String))
    not_covered          it has code, or it is abstract with implementations in the
                         library, but neither it nor any override was run
    no_code              abstract or native, with no implementation in the library
    generated            enum values()/valueOf(): generated by the compiler and
                         left out of JaCoCo reports
    not_reported         not in the JaCoCo report for another reason, e.g. a class
                         that was not compiled in the coverage build

Overrides come from api-overrides.csv (step 4); without it, overrides are not
considered. Fields are not included (they have no coverage).

OUTPUT (in the workspace):
    api-coverage.csv   api_id, kind, visibility, deprecated, status, overrides,
                       overrides_covered, instruction_missed, instruction_covered,
                       branch_missed, branch_covered, line_missed, line_covered,
                       complexity_missed, complexity_covered
                       (counters are of the API's own body)

USAGE:
    python -m ossbridge_pipeline.api_coverage --library commons-codec:commons-codec --version 1.17.1
================================================================================
"""

import argparse
import csv
import sys
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict

from .workspace import Workspace

COUNTERS = ["instruction", "branch", "line", "complexity"]
COUNTER_COLUMNS = [f"{c}_{kind}" for c in COUNTERS for kind in ("missed", "covered")]
API_COVERAGE_COLUMNS = (["api_id", "kind", "visibility", "deprecated", "status", "overrides", "overrides_covered"]
                        + COUNTER_COLUMNS)
STATUSES = ["covered", "covered_by_override", "not_covered", "no_code", "generated", "not_reported"]


def method_coverage(coverage_xml):
    """{api_id: {instruction_missed: .., ...}} for every method in a JaCoCo XML report.

    JaCoCo names classes a/b/Outer$Inner and constructors <init>, so the ids use the
    same format as apis.csv: a.b.Outer$Inner.<init>(I)V
    """
    methods = {}
    # iterparse: reports of large libraries are tens of MB
    for _, el in ET.iterparse(coverage_xml, events=("end",)):
        if el.tag != "class":
            continue
        class_name = el.get("name").replace("/", ".")
        for method in el.findall("method"):
            values = dict.fromkeys(COUNTER_COLUMNS, 0)
            for counter in method.findall("counter"):
                kind = counter.get("type").lower()
                if kind in COUNTERS:
                    values[f"{kind}_missed"] = int(counter.get("missed"))
                    values[f"{kind}_covered"] = int(counter.get("covered"))
            methods[f"{class_name}.{method.get('name')}{method.get('desc')}"] = values
        el.clear()
    return methods


def read_overrides(overrides_csv):
    overrides = defaultdict(list)
    if overrides_csv and overrides_csv.exists():
        with open(overrides_csv, newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                overrides[row["api_id"]].append(row["override_id"])
    return overrides


def match(apis_csv, coverage_xml, out_csv, overrides_csv=None):
    """Write api-coverage.csv; returns counts per status."""
    coverage = method_coverage(coverage_xml)
    overrides = read_overrides(overrides_csv)
    with open(apis_csv, newline="", encoding="utf-8") as f:
        apis = [r for r in csv.DictReader(f) if r["kind"] in ("method", "constructor")]

    def is_covered(method_id):
        counts = coverage.get(method_id)
        return counts is not None and counts["instruction_covered"] > 0

    statuses = Counter()
    with open(out_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=API_COVERAGE_COLUMNS)
        writer.writeheader()
        for api in apis:
            counts = coverage.get(api["api_id"])
            impls = overrides.get(api["api_id"], [])
            impls_covered = sum(1 for o in impls if is_covered(o))
            if counts is not None and counts["instruction_covered"] > 0:
                status = "covered"
            elif impls_covered:
                status = "covered_by_override"
            elif counts is not None:
                status = "not_covered"
            elif api["abstract"] == "true":
                # An abstract method with implementations that the tests never run is not covered.
                status = "not_covered" if impls else "no_code"
            elif api["class_kind"] == "enum" and api["member"] in ("values", "valueOf") and api["static"] == "true":
                status = "generated"
            else:
                status = "not_reported"
            statuses[status] += 1
            writer.writerow({"api_id": api["api_id"], "kind": api["kind"], "visibility": api["visibility"],
                             "deprecated": api["deprecated"], "status": status, "overrides": len(impls),
                             "overrides_covered": impls_covered,
                             **(counts or dict.fromkeys(COUNTER_COLUMNS, ""))})

    reachable = statuses["covered"] + statuses["covered_by_override"] + statuses["not_covered"]
    return {"apis": len(apis), **{s: statuses[s] for s in STATUSES},
            "covered_pct": round(100 * (statuses["covered"] + statuses["covered_by_override"]) / reachable, 1)
            if reachable else None}


def run(workspace):
    """Step 6 for a workspace with apis.csv (step 4) and coverage.xml (step 5)."""
    for path, step in ((workspace.apis_csv, "4 (public_api)"), (workspace.coverage_xml, "5 (coverage)")):
        if not path.exists():
            raise FileNotFoundError(f"{path} not found; run step {step} first")
    return match(workspace.apis_csv, workspace.coverage_xml, workspace.api_coverage_csv,
                 workspace.api_overrides_csv)


def main():
    parser = argparse.ArgumentParser(description="Coverage of each API of a library version")
    parser.add_argument("--library", required=True, help="groupId:artifactId")
    parser.add_argument("--version", required=True)
    args = parser.parse_args()
    try:
        summary = run(Workspace(args.library, args.version))
    except FileNotFoundError as e:
        sys.exit(str(e))
    print("  " + ", ".join(f"{k}: {v}" for k, v in summary.items()))


if __name__ == "__main__":
    main()
